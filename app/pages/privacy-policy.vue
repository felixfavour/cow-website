      <h2 id="voice-transcription">Voice Transcription</h2>
      <p>
        Live voice transcription listens to what is being said and turns it into
        text, so that scripture references spoken aloud can be recognised and
        brought up automatically. Because it involves a live microphone in a room
        that may contain many people, We describe it separately and in full.
      </p>
      <ul>
        <li>
          <p>
            <strong>It is opt-in and manual.</strong> Transcription is available
            on the Teams plan and only runs after a User explicitly starts it in
            the Application and grants microphone permission. It stops when the
            User stops it, when the session ends, or when the plan's
            transcription allowance is exhausted.
          </p>
        </li>
        <li>
          <p>
            <strong>What is captured.</strong> Audio from the microphone You
            select, streamed in short chunks while transcription is running. We
            do not capture audio when transcription is not running.
          </p>
        </li>
        <li>
          <p>
            <strong>Where it goes.</strong> Audio is sent over an encrypted
            connection to our servers, which relay it to Deepgram, our
            speech-recognition provider, and return the resulting text to Your
            Device. Deepgram processes the audio on our instructions as a
            Service Provider.
          </p>
        </li>
        <li>
          <p>
            <strong>What We keep.</strong> Audio is processed in transit to
            produce text and is not retained as a recording by Us after the
            session. Transcript text is held in the Application for the duration
            of Your session so You can see and use it. We retain the number of
            transcription seconds used, in order to apply Your plan's allowance.
            <!-- CONFIRM: if the backend persists transcript segments or audio for any period, state that period here instead. -->
          </p>
        </li>
        <li>
          <p>
            <strong>What is said may be sensitive.</strong> A live service can
            include prayer requests, testimonies, pastoral remarks, and other
            deeply personal speech from people who are not Cloud of Worship
            users. Anything within range of the microphone while transcription is
            running will be transmitted for processing.
          </p>
        </li>
        <li>
          <p>
            <strong>Your responsibility as the account holder.</strong> If You
            enable transcription in a gathering, You are the controller of that
            audio in relation to the people present. You are responsible for
            telling them that transcription is in use, for obtaining any consent
            Your local law requires, and for placing the microphone
            appropriately. Do not enable transcription during confidential
            pastoral conversations, counselling, or any session where those
            present would not expect it.
          </p>
        </li>
      </ul>

